#!/usr/bin/env python3
"""Carry original-frame-2 fur detail on reviewed generated frames 105..124.

Exact MOMO016 v2 algorithm, limited to 832x768 assets. No alpha/body geometry,
output blur, gain normalization or sharpening. Source detail and its fixed safe
material mask are sampled together; the legacy destination safety mask also applies.
Requires Python/Pillow/NumPy/SciPy and precomputed macOS Vision flow cache.

--original is the clear original frame-0002.png; --generated contains graded
frame-0105.png..0124.png. --flow-cache contains backward-0105.bin..0124.bin,
832x768x2 little-endian float32, generated by prepare-rabbit-loop-flow.swift with
SOURCE=original2 and TARGET=generatedN. Reuse reviewed frame112 backward.bin
from the existing exit motion cache. This tool does not compute/change flow.
--out must be a fresh evidence directory. It writes frames/, metrics and contact.
This is asset-specific postprocessing, not a generic reconstruction algorithm;
phase drift and remaining source material differences require temporal review.
"""
import argparse
from pathlib import Path
import numpy as np,json
from PIL import Image,ImageDraw
from scipy.ndimage import map_coordinates,gaussian_filter,distance_transform_edt
p=argparse.ArgumentParser(description=__doc__)
for key in ['original','generated','flow-cache','out']:p.add_argument('--'+key,type=Path,required=True)
q=p.parse_args()
if q.out.exists():raise ValueError('Output directory must not exist; never overwrite reviewed candidates')
B=np.asarray(Image.open(q.original).convert('RGBA'),dtype=np.float32)/255
if B.shape!=(768,832,4):raise ValueError('Only the reviewed 832x768 rabbit assets are supported')
h,w=B.shape[:2];y,x=np.mgrid[:h,:w].astype(np.float32)
def sample(im,xx,yy,order=1):
 if im.ndim==2:return map_coordinates(im,[yy,xx],order=order,mode='nearest')
 return np.stack([map_coordinates(im[...,c],[yy,xx],order=order,mode='nearest') for c in range(im.shape[2])],-1)
clip=lambda a:np.clip(a,0,1)
V=q.out;V.mkdir(parents=True);out=V/'frames';out.mkdir()
bp=B.copy();bp[...,:3]*=bp[...,3:4]
sourceDetail=bp[...,:3]-gaussian_filter(bp[...,:3],(1,1,0))
sourceMask=clip((B[...,:3].min(2)-.55)/.12)*clip((.23-(B[...,0]-B[...,2]))/.06)
sourceMask*=clip((distance_transform_edt(B[...,3]>.98)-18)/10)
for cx,cy,r in [(400,350,43),(278,338,28),(301,400,36)]:sourceMask*=clip((np.hypot(x-cx,y-cy)-r-5)/12)
sourceMask*=clip((430-y)/14)+((y>515)*clip((y-515)/14));sourceMask=clip(sourceMask)
Image.fromarray(np.uint8(sourceMask*255),'L').save(V/'source-safe-mask.png')
rows=[];ims=[]
for n in range(105,125):
 A=np.asarray(Image.open(q.generated/f'frame-{n:04d}.png').convert('RGBA'),dtype=np.float32)/255
 if A.shape!=B.shape:raise ValueError('Generated dimensions differ')
 g=np.fromfile(q.flow_cache/f'backward-{n:04d}.bin',dtype=np.float32).reshape(h,w,2);g=gaussian_filter(g,(1,1,0))
 bx=x.copy();by=y.copy()
 for _ in range(4):
  bg=sample(g,bx,by);bx=x-bg[...,0];by=y-bg[...,1]
 detailB=sample(sourceDetail,bx,by,3)
 sourceValid=clip(sample(sourceMask,bx,by,1))
 premA=A[...,:3]*A[...,3:4]
 detailA=premA-gaussian_filter(premA,(1,1,0))
 mask=clip((A[...,:3].min(2)-.55)/.12)*clip((.23-(A[...,0]-A[...,2]))/.06)
 mask*=clip((distance_transform_edt(A[...,3]>.95)-10)/8)
 for cx,cy,r in [(400,350,43),(278,338,28),(301,400,36)]:mask*=clip((np.hypot(x-cx,y-cy)-r)/12)
 mask*=clip((440-y)/14)+((y>500)*clip((y-500)/14));mask=clip(mask)*sourceValid
 weight=clip((n-105)/7);weight=weight*weight*(3-2*weight)
 C=A.copy();delta=(detailB-detailA)/np.maximum(A[...,3:4],1e-6)
 C[...,:3]=clip(A[...,:3]+delta*mask[...,None]*weight)
 pix=np.uint8(C*255+.5);Image.fromarray(pix).save(out/f'frame-{n:04d}.png')
 originalPix=np.uint8(A*255+.5)
 if not np.array_equal(pix[...,3],originalPix[...,3]):raise RuntimeError('Alpha changed')
 if not np.array_equal(pix[mask==0],originalPix[mask==0]):raise RuntimeError('Protected RGB changed')
 if not np.isfinite(C).all():raise RuntimeError('Nonfinite output')
 er=(mask>.99);rows.append({'source':n,'weight':float(weight),'meanDelta':np.mean((C-A)[...,:3][er],axis=0).tolist(),'maxChannelDelta':float(np.max(np.abs(C-A)[...,:3][er])),'alphaExact':True,'protectedRGBExact':True})
 if n in [105,107,109,112,116,120,124]:ims.append((n,Image.fromarray(pix)))
sheet=Image.new('RGB',(1400,400),'#d8d9cf')
for i,(n,im) in enumerate(ims):
 bg=Image.new('RGBA',(200,400),'#d8d9cf');crop=im.crop((255,190,455,590));bg.alpha_composite(crop);sheet.paste(bg.convert('RGB'),(i*200,0));ImageDraw.Draw(sheet).text((i*200,0),str(n),fill='black')
sheet.save(V/'contact.jpg',quality=98)
(V/'metrics.json').write_text(json.dumps(rows,indent=2))
